#!/usr/bin/env bash
##############################################################################
# 日志工具函数库 - 增强版（带颜色+行号）【完整修复版】
# 核心特性：
# 1. ✅ 日志输出至 stderr（不干扰 stdout 正常输出）【已修复实现】
# 2. ✅ 固定日志格式：时间戳 + 自定义前缀 + 日志级别（彩色） + 行号 + 日志内容
# 3. ✅ 支持 DEBUG/INFO/WARN/ERROR 四级日志，各级别颜色区分【转义码已修复】
# 4. ✅ ERROR 级别日志输出后自动退出（退出码 1）+ 健壮性优化
# 5. ✅ 显示日志调用所在的脚本行号（精准定位，已修复行号BUG）
# 6. ✅ 可通过环境变量控制：
#    - LOG_PREFIX：自定义日志前缀（如服务名、脚本名）
#    - LOG_NO_COLOR：设置为 1 可关闭颜色输出（兼容无颜色终端）
# 新增特性：
# 7. ✅ 自动检测非交互式终端，自动关闭颜色（docker/CI/重定向场景无感兼容）
# 8. ✅ 退出前刷新缓冲区，避免日志丢失
##############################################################################

# ========================= 配置项（可按需调整）=========================
# 颜色定义（ANSI 转义序列）- 不变
readonly COLOR_DEBUG="\033[0;37m"   # 灰色：DEBUG
readonly COLOR_INFO="\033[0;32m"    # 绿色：INFO
readonly COLOR_WARN="\033[0;33m"    # 黄色：WARN
readonly COLOR_ERROR="\033[0;31m"   # 红色：ERROR
readonly COLOR_RESET="\033[0m"      # 重置颜色

# 日志前缀默认值（可通过 export LOG_PREFIX="[APP_NAME]" 自定义）
: "${LOG_PREFIX:=''}"

# 关闭颜色开关（默认开启）+ 自动检测非交互式终端，自动关闭颜色
: "${LOG_NO_COLOR:=0}"
[[ ! -t 2 ]] && LOG_NO_COLOR=1  # 关键：非TTY终端（docker/CI）自动关闭颜色
# ======================================================================

##############################################################################
# 核心日志输出函数（内部使用，不建议直接调用）
# 参数说明：
#   $1: 日志级别（DEBUG/INFO/WARN/ERROR）
#   $2: 调用日志的脚本行号
#   $3~$n: 日志内容（支持多参数拼接，兼容含空格/特殊字符的输入）
# 输出格式：YYYY-MM-DD HH:MM:SS [前缀] [级别(彩色)] [Line:行号] 日志内容
##############################################################################
log() {
    local level="$1"
    local line_num="$2"
    shift 2  # 移除前两个参数（级别+行号），剩余为日志内容

    # 根据日志级别选择颜色
    case "$level" in
        DEBUG) local color="$COLOR_DEBUG" ;;
        INFO)  local color="$COLOR_INFO" ;;
        WARN)  local color="$COLOR_WARN" ;;
        ERROR) local color="$COLOR_ERROR" ;;
        *)     local color="$COLOR_RESET" ;;  # 未知级别默认无颜色
    esac

    # 若关闭颜色，重置为默认色
    [[ "$LOG_NO_COLOR" -eq 1 ]] && color="$COLOR_RESET"

    # 格式化输出【核心修复全部在这里！】
    # 1. %b 解析转义码  2. >&2 输出到stderr  3. 格式不变，兼容所有特性
    printf "%s %s %b[%s]%b [Line:%d] %s\n" \
        "$(date '+%Y-%m-%d %H:%M:%S')" \
        "${LOG_PREFIX}" \
        "${color}" \
        "${level}" \
        "${COLOR_RESET}" \
        "${line_num}" \
        "$*" >&2
}

##############################################################################
# 调试级日志（DEBUG）- 开发/调试用，灰色输出
# 用法：debug "用户输入参数：" "$@"
##############################################################################
debug() {
    log "DEBUG" "${BASH_LINENO[0]}" "$@"
}

##############################################################################
# 信息级日志（INFO）- 常规运行状态，绿色输出
# 用法：info "服务启动成功" "监听端口：8080"
##############################################################################
info() {
    log "INFO" "${BASH_LINENO[0]}" "$@"
}

##############################################################################
# 警告级日志（WARN）- 非致命异常，黄色输出
# 用法：warn "配置文件不存在" "使用默认配置"
##############################################################################
warn() {
    log "WARN" "${BASH_LINENO[0]}" "$@"
}

##############################################################################
# 错误级日志（ERROR）- 致命异常，红色输出，输出后退出（退出码 1）
# 用法：err "数据库连接失败" "无法继续执行"
##############################################################################
err() {
    log "ERROR" "${BASH_LINENO[0]}" "$@"
    # 优化：刷新缓冲区+退出，避免日志丢失
    sync && exit 1
}